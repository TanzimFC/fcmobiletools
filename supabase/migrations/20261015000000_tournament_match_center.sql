-- Match Center: player-driven results (report -> opponent confirms -> admin only on disputes).
alter table public.tournament_players
  add column if not exists account_id uuid,
  add column if not exists discord_handle text not null default '',
  add column if not exists fc_uid text not null default '';
create index if not exists tournament_players_account_idx on public.tournament_players(account_id);

create table if not exists public.tournament_match_reports (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.tournament_matches(id) on delete cascade,
  reporter_player_id bigint not null references public.tournament_players(id) on delete cascade,
  player1_score int not null check (player1_score >= 0),
  player2_score int not null check (player2_score >= 0),
  screenshot_url text not null,
  status text not null default 'pending' check (status in ('pending','confirmed','disputed','escalated','resolved','superseded')),
  response_note text not null default '',
  expires_at timestamptz not null default now() + interval '24 hours',
  created_at timestamptz not null default now(), responded_at timestamptz
);
create index if not exists tmr_match_idx on public.tournament_match_reports(match_id, created_at desc);
create index if not exists tmr_status_idx on public.tournament_match_reports(status) where status in ('disputed','escalated');

create table if not exists public.tournament_match_messages (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.tournament_matches(id) on delete cascade,
  sender_player_id bigint not null references public.tournament_players(id) on delete cascade,
  kind text not null default 'chat' check (kind in ('chat','schedule')),
  body text not null check (char_length(body) between 1 and 400),
  proposed_at timestamptz, created_at timestamptz not null default now()
);
create index if not exists tmm_match_idx on public.tournament_match_messages(match_id, created_at);

-- Service-role (worker) access only; no public policies.
alter table public.tournament_match_reports enable row level security;
alter table public.tournament_match_messages enable row level security;
