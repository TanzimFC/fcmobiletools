const PUBLIC_REDEEM_PATH = '/api/public/redeem-codes';
const PUBLIC_REDEEM_TTL = 60; // seconds the edge keeps one snapshot; admin writes purge this cache

async function redeemIdentity(request, env) {
  if (await authenticated(request, env)) return { role: 'admin', actor: 'admin' };
  const creator = await creatorRecord(request, env);
  if (creator) return { role: 'creator', actor: 'creator:' + creator.username };
  return null;
}

const purgePublicRedeemCache = (origin) =>
  caches.default.delete(new Request(origin + PUBLIC_REDEEM_PATH)).catch(() => false);

// One D1 read per TTL per data centre, no matter how many visitors are on the page.
async function publicRedeemSnapshot(env, ctx, origin) {
  const cache = caches.default;
  const key = new Request(origin + PUBLIC_REDEEM_PATH);
  const hit = await cache.match(key);
  if (hit) return { payload: await hit.json(), etag: hit.headers.get('etag') };

  const payload = await publicPayload(await d1(env));
  const etag = `W/"${payload.codes.length}-${payload.updatedAt || 0}-${payload.serverDate}"`;
  const stored = new Response(JSON.stringify(payload), {
    headers: { 'content-type': 'application/json; charset=utf-8', 'cache-control': `public, max-age=${PUBLIC_REDEEM_TTL}`, etag },
  });
  ctx?.waitUntil?.(cache.put(key, stored));
  return { payload, etag };
}

async function publicRedeemApi(request, env, ctx, url) {
  if (request.method !== 'GET' && request.method !== 'HEAD') return json({ error: 'Method not allowed.' }, 405, { allow: 'GET, HEAD' });
  try {
    const { payload, etag } = await publicRedeemSnapshot(env, ctx, url.origin);
    const headers = {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': `public, max-age=${PUBLIC_REDEEM_TTL}, stale-while-revalidate=60`,
      etag,
    };
    if (request.headers.get('if-none-match') === etag) return new Response(null, { status: 304, headers });
    return new Response(request.method === 'HEAD' ? null : JSON.stringify(payload), { headers });
  } catch (error) {
    console.error('[REDEEM_PUBLIC]', error?.message);
    return json({ error: 'Redeem codes are temporarily unavailable.' }, 503);
  }
}

function redeemErrorResponse(error) {
  if (error instanceof RedeemError) return json({ error: error.message, ...error.extra }, error.status);
  if (error instanceof SyntaxError) return json({ error: 'Request body must be valid JSON.' }, 400);
  console.error('[REDEEM_ADMIN]', error?.message);
  return json({ error: error?.message || 'Unexpected error.' }, 500);
}

// Handles /api/admin/redeem* and /api/creator/redeem*. Admins and creators can
// read and write; only admins can delete.
async function redeemAdminApi(request, env, url) {
  const identity = await redeemIdentity(request, env);
  if (!identity) return json({ error: 'Authentication required.' }, 401);
  const sub = url.pathname.replace(/^\/api\/(?:admin|creator)\/redeem/, '').replace(/\/$/, '') || '/';
  const method = request.method;

  try {
    const db = await d1(env);

    if (method === 'GET' && sub === '/') return json({ ...(await listAdminCodes(db)), role: identity.role });
    if (method === 'GET' && sub === '/export') {
      const { codes } = await listAdminCodes(db);
      return new Response(codesToCsv(codes), { headers: {
        'content-type': 'text/csv; charset=utf-8',
        'content-disposition': `attachment; filename="redeem-codes-${new Date().toISOString().slice(0, 10)}.csv"`,
        'cache-control': 'no-store',
      } });
    }
    if (method !== 'POST' && method !== 'DELETE') return json({ error: 'Method not allowed.' }, 405);
    if (method === 'POST' && !(request.headers.get('content-type') || '').includes('application/json')) return json({ error: 'Send JSON.' }, 415);

    let result;
    if (method === 'POST' && sub === '/') {
      result = await saveRedeemRecord(db, await request.json(), identity.actor);
    } else if (method === 'DELETE' && sub === '/') {
      if (identity.role !== 'admin') return json({ error: 'Only admins can delete codes.' }, 403);
      result = await deleteRedeemCode(db, url.searchParams.get('code') || '');
    } else if (method === 'POST' && sub === '/bulk') {
      const body = await request.json();
      if (body.action === 'create') result = await bulkCreateRedeem(db, body.items, identity.actor);
      else {
        if (body.action === 'delete' && identity.role !== 'admin') return json({ error: 'Only admins can delete codes.' }, 403);
        result = await bulkRedeemAction(db, body.action, body.codes, identity.actor);
      }
    } else {
      return json({ error: 'Not found.' }, 404);
    }

    await purgePublicRedeemCache(url.origin);
    return json({ ok: true, ...result });
  } catch (error) {
    return redeemErrorResponse(error);
  }
}

// The page itself is static HTML. The Worker injects the live snapshot into it,
// so the first paint already shows today's codes (no skeleton flash, no extra
// round trip) and crawlers get fresh structured data.
async function redeemPage(request, env, ctx, url) {
  const asset = await env.ASSETS.fetch(new Request(new URL('/redeem-codes/', url), { method: 'GET', headers: request.headers }));
  if (!asset.ok || !(asset.headers.get('content-type') || '').includes('text/html')) return asset;

  const headers = new Headers(asset.headers);
  headers.set('cache-control', 'no-store, max-age=0, must-revalidate');
  headers.set('x-fcmobiletools-page', 'redeem-live');
  headers.delete('content-length');
  headers.delete('etag');

  let snapshot = null;
  try { snapshot = (await publicRedeemSnapshot(env, ctx, url.origin)).payload; } catch (error) { console.error('[REDEEM_PAGE]', error?.message); }
  if (!snapshot) return new Response(asset.body, { status: asset.status, headers });

  const bootstrap = safeScriptJson(snapshot);
  const structured = safeScriptJson(redeemJsonLd(snapshot.codes, url.origin, snapshot.updatedAt || undefined));
  return new HTMLRewriter()
    .on('script#rx-bootstrap', { element(el) { el.setInnerContent(bootstrap, { html: true }); } })
    .on('script#rx-ld', { element(el) { el.setInnerContent(structured, { html: true }); } })
    .transform(new Response(asset.body, { status: asset.status, headers }));
}


const IMAGE_UPLOAD_MAX_BYTES = 8 * 1024 * 1024;
const IMAGE_UPLOAD_DEFAULT_EXPIRATION_DAYS = 30;
const IMAGE_UPLOAD_HOST = /^i\.ibb\.co(?:\.com)?$/i;

async function detectUploadedImageType(file) {
  const bytes = new Uint8Array(await file.slice(0, 12).arrayBuffer());
  if (bytes.length >= 3 && bytes[0] === 0xff && bytes[1] === 0xd8 && bytes[2] === 0xff) return 'image/jpeg';
  if (bytes.length >= 8 && bytes[0] === 0x89 && bytes[1] === 0x50 && bytes[2] === 0x4e && bytes[3] === 0x47 &&
      bytes[4] === 0x0d && bytes[5] === 0x0a && bytes[6] === 0x1a && bytes[7] === 0x0a) return 'image/png';
  if (bytes.length >= 6) {
    const signature = String.fromCharCode(...bytes.slice(0, 6));
    if (signature === 'GIF87a' || signature === 'GIF89a') return 'image/gif';
  }
  if (bytes.length >= 12 &&
      String.fromCharCode(...bytes.slice(0, 4)) === 'RIFF' &&
      String.fromCharCode(...bytes.slice(8, 12)) === 'WEBP') return 'image/webp';
  return null;
}

async function reserveImageUploadQuota(origin, accountId) {
  const now = Date.now();
  const cache = caches.default;
  const windows = [
    { key: 'burst', duration: 10 * 60 * 1000, limit: 10 },
    { key: 'daily', duration: 24 * 60 * 60 * 1000, limit: 50 }
  ];

  for (const window of windows) {
    const bucket = Math.floor(now / window.duration);
    const keyUrl = new URL('/_internal/image-upload-rate/' +
      encodeURIComponent(accountId) + '/' + window.key + '/' + bucket, origin);
    const key = new Request(keyUrl.toString());
    const previous = await cache.match(key);
    const count = previous ? Number((await previous.json().catch(() => ({}))).count || 0) : 0;
    if (count >= window.limit) return false;
    await cache.put(key, new Response(JSON.stringify({ count: count + 1 }), {
      headers: {
        'content-type': 'application/json; charset=utf-8',
        'cache-control': 'public, max-age=' + (Math.ceil(window.duration / 1000) + 60)
      }
    }));
  }
  return true;
}

async function imageUploadApi(request, env, url) {
  if (request.method !== 'POST') return json({ error: 'Method not allowed.' }, 405, { allow: 'POST' });

  const originHeader = request.headers.get('origin');
  if (originHeader) {
    try {
      if (new URL(originHeader).origin !== url.origin) return json({ error: 'Request not allowed.' }, 403);
    } catch {
      return json({ error: 'Request not allowed.' }, 403);
    }
  }

  const context = await accountContext(request, env);
  if (!context) return json({ error: 'Sign in to upload an image.' }, 401);
  const { account, user } = context;
  if (!user.email_confirmed_at) return json({ error: 'Verify your email before uploading images.' }, 403);
  if (['closed', 'fraud_removed', 'frozen', 'restricted'].includes(account.state)) {
    return json({ error: 'This account cannot upload images right now.' }, 403);
  }
  if (!String(env.IMAGEBB_API_KEY || '').trim()) {
    console.error('[IMAGE_UPLOAD] Upload service is not configured.');
    return json({ error: 'Image uploads are temporarily unavailable. Please try again later.' }, 503);
  }

  const contentType = request.headers.get('content-type') || '';
  if (!contentType.toLowerCase().includes('multipart/form-data')) {
    return json({ error: 'Choose an image file to upload.' }, 415);
  }

  const contentLength = Number(request.headers.get('content-length') || 0);
  if (contentLength > IMAGE_UPLOAD_MAX_BYTES + 128 * 1024) {
    return json({ error: 'Choose an image smaller than 8 MB.' }, 413);
  }

  let fields;
  try {
    fields = await request.formData();
  } catch {
    return json({ error: 'The upload could not be read. Please choose the image again.' }, 400);
  }

  const file = fields.get('file');
  if (!file || typeof file.arrayBuffer !== 'function' || typeof file.size !== 'number' || file.size <= 0) {
    return json({ error: 'Choose an image file to upload.' }, 400);
  }
  if (file.size > IMAGE_UPLOAD_MAX_BYTES) {
    return json({ error: 'Choose an image smaller than 8 MB.' }, 413);
  }

  let detectedType;
  try { detectedType = await detectUploadedImageType(file); } catch {}
  if (!detectedType) {
    return json({ error: 'Use a JPG, PNG, WebP, or GIF image.' }, 415);
  }
  const declaredType = String(file.type || '').toLowerCase();
  if (declaredType && declaredType !== 'application/octet-stream' && declaredType !== detectedType &&
      !(detectedType === 'image/jpeg' && declaredType === 'image/jpg')) {
    return json({ error: 'The selected file does not appear to be a valid image.' }, 415);
  }

  // League crests and player avatars need to stay available for the life of a listing.
  // Other upload callers keep the existing temporary-expiry default.
  const permanent = fields.get('permanent') === 'true';
  let expirationDays = Number.parseInt(String(fields.get('expirationDays') || ''), 10);
  if (!Number.isInteger(expirationDays)) expirationDays = IMAGE_UPLOAD_DEFAULT_EXPIRATION_DAYS;
  expirationDays = Math.max(1, Math.min(180, expirationDays));
  const expirationSeconds = expirationDays * 24 * 60 * 60;

  try {
    if (!(await reserveImageUploadQuota(url.origin, account.id))) {
      return json({ error: 'You have reached the upload limit. Please try again later.' }, 429);
    }
  } catch (error) {
    console.error('[IMAGE_UPLOAD] Rate limit check failed.');
    return json({ error: 'Uploads are temporarily unavailable. Please try again later.' }, 503);
  }

  const safeName = String(file.name || 'image')
    .replace(/[^\w.-]+/g, '-')
    .replace(/^\.+/, '')
    .slice(0, 80) || 'image';
  const outgoing = new FormData();
  outgoing.append('image', new File([file], safeName, { type: detectedType }), safeName);

  let upstream;
  let result;
  try {
    const endpoint = new URL('https://api.imgbb.com/1/upload');
    endpoint.searchParams.set('key', String(env.IMAGEBB_API_KEY).trim());
    if (!permanent) endpoint.searchParams.set('expiration', String(expirationSeconds));
    upstream = await fetch(endpoint.toString(), { method: 'POST', body: outgoing });
    result = await upstream.json().catch(() => null);
  } catch {
    console.error('[IMAGE_UPLOAD] Upload request failed.');
    return json({ error: 'The image could not be uploaded. Please try again.' }, 503);
  }

  const image = result?.data;
  if (!upstream.ok || result?.success !== true || !image?.url) {
    console.warn('[IMAGE_UPLOAD] Upload service returned status ' + upstream.status + '.');
    return json({ error: 'The image could not be uploaded. Please try again.' }, 503);
  }

  let directUrl;
  try {
    directUrl = new URL(String(image.url));
    if (directUrl.protocol !== 'https:' || !IMAGE_UPLOAD_HOST.test(directUrl.hostname)) throw new Error('Invalid image host.');
  } catch {
    console.warn('[IMAGE_UPLOAD] Upload response did not contain a valid image URL.');
    return json({ error: 'The image could not be uploaded. Please try again.' }, 503);
  }

  const appliedExpiration = Number(image.expiration);
  if (permanent && appliedExpiration !== 0) {
    console.warn('[IMAGE_UPLOAD] Permanent upload was not confirmed by the image host.');
    return json({ error: 'The image host did not confirm this upload without an expiry. Please try again.' }, 503);
  }
  if (!permanent && (!Number.isFinite(appliedExpiration) || appliedExpiration < 60)) {
    console.warn('[IMAGE_UPLOAD] Automatic image expiry was not confirmed.');
    return json({ error: 'The image could not be uploaded with temporary storage. Please try again.' }, 503);
  }

  return json({
    ok: true,
    image: {
      url: directUrl.toString(),
      width: Math.max(0, Number(image.width) || 0),
      height: Math.max(0, Number(image.height) || 0),
      size: Math.max(0, Number(image.size) || file.size),
      permanent,
      expirationDays: permanent ? null : Math.max(1, Math.ceil(appliedExpiration / (24 * 60 * 60))),
      expiresAt: permanent ? null : new Date(Date.now() + appliedExpiration * 1000).toISOString()
    }
  });
}

